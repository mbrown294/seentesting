export function filterOptions(options: TestingOption[], filters: {
  audience?: string
  setting?: string
  tags?: string[]
}): TestingOption[] {
  return options.filter(opt => {
    if (filters.audience && filters.audience !== 'all') {
      const aud = Array.isArray(opt.audience) ? opt.audience : [opt.audience]
      if (!aud.includes(filters.audience as any)) return false
    }
    if (filters.setting && filters.setting !== 'all') {
      if (opt.setting !== filters.setting) return false
    }
    if (filters.tags && filters.tags.length > 0) {
      const hasTag = filters.tags.some(t => opt.matchTags.includes(t))
      if (!hasTag) return false
    }
    return true
  })
}

export function scoreOptions(options: TestingOption[], answers: {
  priority?: string
  goal?: string
}): TestingOption[] {
  const scored = options.map(opt => {
    let score = 0
    if (answers.priority === 'lowest-cost') score += opt.headlinePrice.includes('£59') || opt.headlinePrice.includes('£79') ? 3 : 0
    if (answers.priority === 'most-comprehensive') score += opt.matchTags.includes('comprehensive') ? 3 : 0
    if (answers.priority === 'fastest') score += opt.turnaround.includes('instant') || opt.turnaround.includes('min') || opt.turnaround.includes('Same day') ? 3 : 1
    if (answers.priority === 'clinician-guidance') score += opt.clinicianSupport !== 'None' ? 3 : 0
    if (answers.goal === 'egg-count') score += opt.matchTags.includes('ovarian-reserve') ? 3 : 0
    if (answers.goal === 'ovulation') score += opt.matchTags.includes('ovulation') ? 3 : 0
    if (answers.goal === 'sperm') score += opt.matchTags.includes('sperm') ? 3 : 0
    if (answers.goal === 'hormones') score += opt.matchTags.includes('hormone') ? 3 : 0
    if (answers.goal === 'full-picture') score += opt.matchTags.includes('comprehensive') ? 3 : 1
    return { ...opt, score }
  })
  return scored.sort((a, b) => (b as any).score - (a as any).score)
}
